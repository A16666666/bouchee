function slug(s: string) { return norm(s).replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''); }

export const BASE_FOODS: Item[] = R.map(([name, kcal, prot, carbs, fat, fiber, sugars, satFat, cat, por]) => ({
  id: 'b:' + slug(name), kind: 'base', name, cat,
  per100: { kcal, prot, carbs, fat, fiber, ...(sugars != null ? { sugars } : {}), ...(satFat != null ? { satFat } : {}) },
  portions: (por ?? '').split('|').filter(Boolean).map(p => {
    const i = p.lastIndexOf(':'); return { label: p.slice(0, i), grams: Number(p.slice(i + 1)) };
  }),
}));
export const BASE_BY_ID = new Map(BASE_FOODS.map(f => [f.id, f]));
